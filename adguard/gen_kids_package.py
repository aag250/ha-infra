#!/usr/bin/env python3
"""Generate the HA package that controls the Kids restrictions / Kids internet via AdGuard's API.
Run on the NUC. Reads the live Kids client from AdGuard (creds: ~/.adguard-cred, 2 lines).
Prints the package YAML to stdout.
Environment: KIDS_CIDR (kids subnet), HA_ADGUARD_URL (AdGuard base URL as seen from HA, e.g. http://host:8081),
ADGUARD_URL (optional, default http://127.0.0.1:8081). HA needs adguard_user / adguard_password in secrets.yaml."""
import json, os, subprocess
U, P = open(os.path.expanduser('~/.adguard-cred')).read().split('\n')[:2]
B = os.environ.get('ADGUARD_URL', 'http://127.0.0.1:8081') + '/control'   # how this script reaches AdGuard
HOST = os.environ['HA_ADGUARD_URL'] + '/control'                          # how Home Assistant reaches AdGuard
def get(path):
    return json.loads(subprocess.check_output(['curl','-s','-u',f'{U}:{P}',f'{B}/{path}']))
client = next(c for c in get('clients')['clients'] if c['name'] == 'Kids')
CIDR = os.environ['KIDS_CIDR']
assert CIDR in client['ids']
acc = get('access/list')
assert not acc['allowed_clients'] and not acc['disallowed_clients'], 'access list not empty; refusing to overwrite'

def payload(use_global):
    c = dict(client, use_global_settings=use_global, use_global_blocked_services=use_global)
    s = json.dumps({'name': 'Kids', 'data': c}, separators=(',', ':'))
    assert '{{' not in s and '{%' not in s and '{#' not in s
    return s
def access(disallowed):
    return json.dumps({'allowed_clients': [], 'disallowed_clients': disallowed,
                       'blocked_hosts': acc['blocked_hosts']}, separators=(',', ':'))

auth = "    username: !secret adguard_user\n    password: !secret adguard_password\n    content_type: application/json\n    method: post\n"
def rc(name, path, body):
    return f"  {name}:\n    url: {HOST}/{path}\n{auth}    payload: '{body}'\n"

print(f"""# Kids network controls (generated by adguard/gen_kids_package.py; do not hand-edit the payloads).
#  - switch.kids_restrictions: Kids client uses its own restrictions (on) or AdGuard global settings (off).
#      The DoH/VPN/proxy bypass rules (user rules scoped to {CIDR}) stay on in both states.
#  - script.kids_pause_restrictions: restrictions off for input_number.kids_pause_minutes, then back on.
#  - switch.kids_internet: off = AdGuard refuses all DNS from {CIDR} (DNS-level cut-off).
# Needs secrets adguard_user / adguard_password in secrets.yaml.

rest_command:""")
print(rc('kids_restrictions_on', 'clients/update', payload(False)), end='')
print(rc('kids_restrictions_off', 'clients/update', payload(True)), end='')
print(rc('kids_internet_on', 'access/set', access([])), end='')
print(rc('kids_internet_off', 'access/set', access([CIDR])), end='')
print(f"""
rest:
  - resource: {HOST}/clients
    authentication: basic
    username: !secret adguard_user
    password: !secret adguard_password
    scan_interval: 30
    sensor:
      - name: Kids restrictions state
        unique_id: kids_restrictions_state
        value_template: >-
          {{% set k = value_json.clients | selectattr('name', 'eq', 'Kids') | list %}}
          {{{{ 'unknown' if not k else ('off' if k[0].use_global_settings else 'on') }}}}
  - resource: {HOST}/access/list
    authentication: basic
    username: !secret adguard_user
    password: !secret adguard_password
    scan_interval: 30
    sensor:
      - name: Kids internet state
        unique_id: kids_internet_state
        value_template: >-
          {{{{ 'off' if '{CIDR}' in value_json.disallowed_clients else 'on' }}}}

template:
  - switch:
      - name: Kids restrictions
        unique_id: kids_restrictions
        icon: mdi:shield-account
        state: "{{{{ is_state('sensor.kids_restrictions_state', 'on') }}}}"
        availability: "{{{{ states('sensor.kids_restrictions_state') in ['on', 'off'] }}}}"
        turn_on:
          - action: rest_command.kids_restrictions_on
          - delay: 1
          - action: homeassistant.update_entity
            target: {{entity_id: sensor.kids_restrictions_state}}
        turn_off:
          - action: rest_command.kids_restrictions_off
          - delay: 1
          - action: homeassistant.update_entity
            target: {{entity_id: sensor.kids_restrictions_state}}
      - name: Kids internet
        unique_id: kids_internet
        icon: mdi:wifi
        state: "{{{{ is_state('sensor.kids_internet_state', 'on') }}}}"
        availability: "{{{{ states('sensor.kids_internet_state') in ['on', 'off'] }}}}"
        turn_on:
          - action: rest_command.kids_internet_on
          - delay: 1
          - action: homeassistant.update_entity
            target: {{entity_id: sensor.kids_internet_state}}
        turn_off:
          - action: rest_command.kids_internet_off
          - delay: 1
          - action: homeassistant.update_entity
            target: {{entity_id: sensor.kids_internet_state}}

input_number:
  kids_pause_minutes:
    name: Restrictions pause length (minutes)
    min: 1
    max: 240
    step: 1
    initial: 15
    unit_of_measurement: min
    icon: mdi:timer-cog-outline

timer:
  kids_restrictions_pause:
    name: Kids restrictions pause
    icon: mdi:shield-off-outline
    restore: true

script:
  kids_pause_restrictions:
    alias: Pause kids restrictions
    icon: mdi:shield-off-outline
    mode: restart
    sequence:
      - action: switch.turn_off
        target:
          entity_id: switch.kids_restrictions
      - action: timer.start
        target:
          entity_id: timer.kids_restrictions_pause
        data:
          duration: "{{{{ (states('input_number.kids_pause_minutes') | float(15) * 60) | int }}}}"
  kids_resume_restrictions:
    alias: Resume kids restrictions
    icon: mdi:shield-check
    sequence:
      - action: timer.cancel
        target:
          entity_id: timer.kids_restrictions_pause
      - action: switch.turn_on
        target:
          entity_id: switch.kids_restrictions

automation:
  - id: kids_pause_finished
    alias: Kids restrictions - resume when pause ends
    triggers:
      - trigger: event
        event_type: timer.finished
        event_data:
          entity_id: timer.kids_restrictions_pause
    actions:
      - action: switch.turn_on
        target:
          entity_id: switch.kids_restrictions
  - id: kids_pause_cleared
    alias: Kids restrictions - clear pause when turned back on
    triggers:
      - trigger: state
        entity_id: switch.kids_restrictions
        to: "on"
    conditions:
      - condition: state
        entity_id: timer.kids_restrictions_pause
        state: active
    actions:
      - action: timer.cancel
        target:
          entity_id: timer.kids_restrictions_pause""")
